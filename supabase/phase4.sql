-- ---------------------------------------------------------------------
-- 2. Push outbox
--    Database triggers write one row per alert for the partner. The
--    sender's phone sees its own new rows over realtime and asks the
--    send-push Edge Function to deliver them, so alert text is always
--    written here, server-side, never by a client.
-- ---------------------------------------------------------------------
create table if not exists public.push_outbox (
  id            uuid primary key default gen_random_uuid(),
  couple_id     uuid not null references public.couples (id) on delete cascade,
  sender_id     uuid not null references auth.users (id) on delete cascade,
  recipient_id  uuid not null references auth.users (id) on delete cascade,
  kind          text not null,
  title         text not null check (char_length(title) <= 120),
  body          text check (char_length(body) <= 240),
  url           text not null default '/',
  tag           text,
  created_at    timestamptz not null default now(),
  sent_at       timestamptz
);
create index if not exists push_outbox_pending_idx on public.push_outbox (sender_id, created_at) where sent_at is null;

alter table public.push_outbox enable row level security;
drop policy if exists push_outbox_sender_read on public.push_outbox;
create policy push_outbox_sender_read on public.push_outbox for select to authenticated
  using (sender_id = (select auth.uid()));
revoke insert, update, delete on public.push_outbox from anon, authenticated;

-- Push signing keys. Generated by the send-push Edge Function the first
-- time it runs (server-side, with the service role), so nobody ever has
-- to create, copy or paste a key. No policies: browsers can read only the
-- public half, through push_public_key() below.
create table if not exists public.push_vapid_keys (
  id           boolean primary key default true check (id),
  public_key   text not null,
  private_key  text not null,
  created_at   timestamptz not null default now()
);
alter table public.push_vapid_keys enable row level security;
revoke all on public.push_vapid_keys from anon, authenticated;

create or replace function public.push_public_key()
returns text language sql stable security definer set search_path = '' as $$
  select public_key from public.push_vapid_keys where id
$$;

-- Queues an alert for the caller's partner (only if they have a device
-- signed up for alerts). Internal: called by triggers below.
create or replace function public.queue_partner_push(p_kind text, p_title text, p_body text, p_url text, p_tag text default null)
returns void language plpgsql security definer set search_path = '' as $$
declare
  v_me uuid := auth.uid();
  v_couple uuid;
  v_partner uuid;
begin
  if v_me is null then return; end if;
  select couple_id into v_couple from public.profiles where id = v_me;
  if v_couple is null then return; end if;
  select id into v_partner from public.profiles where couple_id = v_couple and id <> v_me limit 1;
  if v_partner is null then return; end if;
  if not exists (select 1 from public.push_subscriptions where user_id = v_partner) then return; end if;
  insert into public.push_outbox (couple_id, sender_id, recipient_id, kind, title, body, url, tag)
  values (v_couple, v_me, v_partner, p_kind, left(p_title, 120), left(p_body, 240), coalesce(p_url, '/'), p_tag);
end $$;

create or replace function public.push_on_activity()
returns trigger language plpgsql security definer set search_path = '' as $$
declare
  v_name text := coalesce((select display_name from public.profiles where id = auth.uid()), 'Your partner');
  v_text text;
begin
  if auth.uid() is null then return new; end if;

  if tg_table_name = 'love_pings' then
    perform public.queue_partner_push(
      case when new.kind::text = 'custom' then 'love' else new.kind::text end,
      case new.kind::text
        when 'thinking_of_you' then v_name || ' is thinking of you 💭'
        when 'need_cuddles'    then v_name || ' needs cuddles 🪫'
        when 'need_hype'       then v_name || ' needs some hype 📣'
        else v_name || ' sent love 💗' end,
      new.message, '/#/spark', 'ping');
  elsif tg_table_name = 'voice_notes' then
    perform public.queue_partner_push('voice_note', v_name || ' sent a voice note 🎙️',
      round(new.duration_ms / 1000.0)::int || ' seconds · tap to listen', '/#/spark', 'voice');
  elsif tg_table_name = 'question_answers' and tg_op = 'INSERT' then
    perform public.queue_partner_push('question_answered', v_name || ' answered today''s question 🔓',
      'Answer yours to see what they said.', '/#/spark', 'question');
  elsif tg_table_name = 'dinner_matches' then
    select title into v_text from public.meal_options where id = new.option_id;
    perform public.queue_partner_push('dinner_match', 'It''s a dinner match! 🍽️',
      coalesce(v_text, 'You both swiped right.'), '/#/spark', 'dinner');
  elsif tg_table_name = 'tasks' then
    if tg_op = 'INSERT' then
      perform public.queue_partner_push('task', 'New bounty from ' || v_name || ' 🪙',
        new.title || ' · ' || new.reward_coins || ' coins', '/#/spark', 'task-' || new.id);
    elsif new.status is distinct from old.status then
      perform public.queue_partner_push('task',
        case new.status
          when 'claimed'  then v_name || ' took a bounty 🙋'
          when 'done'     then v_name || ' finished a bounty ✅'
          when 'approved' then v_name || ' approved your bounty 🪙'
          else v_name || ' updated a bounty' end,
        new.title, '/#/spark', 'task-' || new.id);
    end if;
  elsif tg_table_name = 'coupon_redemptions' and tg_op = 'INSERT' then
    select emoji || ' ' || title into v_text from public.coupons where id = new.coupon_id;
    perform public.queue_partner_push('coupon', v_name || ' redeemed a coupon 🎟️', v_text, '/#/spark', 'coupon');
  elsif tg_table_name = 'memories' and tg_op = 'INSERT' then
    perform public.queue_partner_push('memory', v_name || ' added today''s polaroid 📸',
      coalesce(new.caption, 'Add yours to complete the pair.'), '/#/spark', 'memory');
  elsif tg_table_name = 'tiktok_videos' and tg_op = 'INSERT' then
    perform public.queue_partner_push('tiktok', v_name || ' shared a TikTok 🎬',
      coalesce(new.title, 'Watch it together'), '/#/discover', 'tiktok');
  elsif tg_table_name = 'tiktok_comments' and tg_op = 'INSERT' then
    perform public.queue_partner_push('tiktok', v_name || ' commented on a TikTok 💬',
      left(new.body, 120), '/#/discover', 'tiktok-comment');
  end if;
  return new;
end $$;

do $$
declare t text; ev text;
begin
  for t, ev in select * from (values
      ('love_pings', 'insert'), ('voice_notes', 'insert'), ('question_answers', 'insert'),
      ('dinner_matches', 'insert'), ('tasks', 'insert or update'), ('coupon_redemptions', 'insert'),
      ('memories', 'insert'), ('tiktok_videos', 'insert'), ('tiktok_comments', 'insert')) v(t, ev)
