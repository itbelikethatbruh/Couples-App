-- 1. Row guards for the Discover tables
-- ---------------------------------------------------------------------
create or replace function public.guard_discover_rows()
returns trigger language plpgsql security definer set search_path = '' as $$
begin
  if auth.uid() is null then return new; end if;    -- SQL editor / maintenance

  if tg_table_name = 'tiktok_videos' then
    if tg_op = 'INSERT' then new.sent_by := auth.uid(); else new.sent_by := old.sent_by; new.video_id := old.video_id; end if;
  elsif tg_table_name = 'notes_inbox' then
    if tg_op = 'INSERT' then new.created_by := auth.uid(); else new.created_by := old.created_by; end if;
  elsif tg_table_name = 'checklists' then
    if tg_op = 'INSERT' then new.created_by := auth.uid(); else new.created_by := old.created_by; end if;
  elsif tg_table_name = 'checklist_items' then
    if not exists (select 1 from public.checklists c where c.id = new.checklist_id and c.couple_id = new.couple_id) then
      raise exception 'list not found';
    end if;
    if new.is_done and (tg_op = 'INSERT' or not old.is_done) then new.done_by := auth.uid();
    elsif not new.is_done then new.done_by := null;
    else new.done_by := old.done_by;
    end if;
  end if;
  return new;
end $$;

do $$
declare t text;
begin
  foreach t in array array['tiktok_videos', 'notes_inbox', 'checklists', 'checklist_items'] loop
    execute format('drop trigger if exists %I on public.%I', t || '_guard', t);
    execute format(
      'create trigger %I before insert or update on public.%I
         for each row execute function public.guard_discover_rows()', t || '_guard', t);
  end loop;
end $$;

-- Views, reactions and comments must point at a video in the same couple.
create or replace function public.guard_tiktok_child()
returns trigger language plpgsql security definer set search_path = '' as $$
begin
  if not exists (select 1 from public.tiktok_videos v where v.id = new.video_id and v.couple_id = new.couple_id) then
    raise exception 'video not found';
  end if;
  return new;
end $$;

