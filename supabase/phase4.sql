  end loop;
end $$;

-- Hands the caller's unsent alerts (max 20, newest two hours) to the
-- send-push Edge Function together with the partner's device endpoints,
-- and marks them sent so two calls never deliver the same alert twice.
create or replace function public.claim_push_jobs()
returns table (job_id uuid, job_kind text, job_title text, job_body text, job_url text, job_tag text,
               sub_endpoint text, sub_p256dh text, sub_auth text)
language plpgsql security definer set search_path = '' as $$
begin
  if auth.uid() is null then raise exception 'not authenticated' using errcode = '28000'; end if;
  return query
  with picked as (
    select o.id from public.push_outbox o
    where o.sender_id = auth.uid() and o.sent_at is null and o.created_at > now() - interval '2 hours'
    order by o.created_at
    limit 20
    for update skip locked
  ), jobs as (
    update public.push_outbox o set sent_at = now()
    from picked where o.id = picked.id
    returning o.id, o.recipient_id, o.kind, o.title, o.body, o.url, o.tag
  )
  select j.id, j.kind, j.title, j.body, j.url, j.tag, s.endpoint, s.p256dh, s.auth
  from jobs j
  join public.push_subscriptions s on s.user_id = j.recipient_id;
end $$;

-- Delivery results from send-push: dead endpoints are removed, flaky ones
-- counted (and dropped after 5 failures). Only devices in your couple.
create or replace function public.push_report(p_ok text[], p_gone text[], p_failed text[])
returns void language plpgsql security definer set search_path = '' as $$
declare
  v_couple uuid := (select couple_id from public.profiles where id = auth.uid());
begin
  if v_couple is null then return; end if;
  update public.push_subscriptions s set last_used_at = now(), failed_count = 0
   where s.endpoint = any (coalesce(p_ok, '{}'))
     and s.user_id in (select id from public.profiles where couple_id = v_couple);
  delete from public.push_subscriptions s
   where s.endpoint = any (coalesce(p_gone, '{}'))
     and s.user_id in (select id from public.profiles where couple_id = v_couple);
  update public.push_subscriptions s set failed_count = failed_count + 1
   where s.endpoint = any (coalesce(p_failed, '{}'))
     and s.user_id in (select id from public.profiles where couple_id = v_couple);
  delete from public.push_subscriptions where failed_count >= 5
     and user_id in (select id from public.profiles where couple_id = v_couple);
  delete from public.push_outbox where couple_id = v_couple and created_at < now() - interval '14 days';
end $$;

-- ---------------------------------------------------------------------
-- 3. Universal inbox: one function that files anything shared into the
--    right place. SECURITY INVOKER, so RLS and the guards above apply.
--    The Edge Function decides the kind (no AI, just rules):
--      tiktok → TikTok vault
--      link   → a wishlist board (personal, Restaurants, Vacations, Events)
--      list   → a new checklist
--      note   → one line added to the "Quick notes" list
-- ---------------------------------------------------------------------
create or replace function public.inbox_save(p_source text, p_kind text, p_payload jsonb, p_raw_text text default null, p_raw_url text default null)
returns jsonb language plpgsql security invoker set search_path = '' as $$
declare
  v_me uuid := auth.uid();
  v_couple uuid;
  v_id uuid;
  v_board uuid;
  v_board_kind text;
  v_routed jsonb;
  v_detected text;
  v_pos int;
  v_dup boolean := false;
  v_item jsonb;
begin
  if v_me is null then raise exception 'not authenticated' using errcode = '28000'; end if;
  -- Every lookup below names the couple explicitly: when the Shortcut calls
  -- this through inbox_submit() it runs with owner rights, so RLS alone
  -- would not scope it.
  v_couple := (select couple_id from public.profiles where id = v_me);
  if v_couple is null then raise exception 'pair with your partner first'; end if;
  if p_source not in ('paste', 'share_sheet', 'apple_notes') then raise exception 'unknown source'; end if;

  if p_kind = 'tiktok' then
    v_detected := 'tiktok';
    insert into public.tiktok_videos (share_url, video_id, title, author_name, thumbnail_url, note)
    values (p_payload ->> 'share_url', p_payload ->> 'video_id', left(p_payload ->> 'title', 300),
            left(p_payload ->> 'author_name', 120), p_payload ->> 'thumbnail_url', left(p_payload ->> 'note', 500))
    on conflict (couple_id, video_id) do nothing
    returning id into v_id;
    if v_id is null then
      v_dup := true;
      select id into v_id from public.tiktok_videos where couple_id = v_couple and video_id = p_payload ->> 'video_id';
    end if;
    v_routed := jsonb_build_object('table', 'tiktok_videos', 'id', v_id, 'duplicate', v_dup);

  elsif p_kind = 'link' then
    v_board_kind := coalesce(p_payload ->> 'board_kind', 'amazon');
    if v_board_kind not in ('amazon', 'restaurants', 'vacations', 'events') then v_board_kind := 'amazon'; end if;
    v_detected := case when p_payload ->> 'store' = 'Amazon' then 'amazon' else 'url' end;
    perform public.ensure_wishlist_boards();
    if v_board_kind = 'amazon' then
      select id into v_board from public.wishlist_boards where couple_id = v_couple and kind = 'amazon' and owner_id = v_me limit 1;
    else
      select id into v_board from public.wishlist_boards where couple_id = v_couple and kind = v_board_kind::public.wishlist_kind and owner_id is null limit 1;
    end if;
    insert into public.wishlist_items (board_id, url, title, image_url, price_cents, currency, store, asin, metadata)
    values (v_board, p_payload ->> 'url',
            left(coalesce(nullif(p_payload ->> 'title', ''), p_payload ->> 'url', 'Saved link'), 300),
            p_payload ->> 'image_url', (p_payload ->> 'price_cents')::bigint,
            coalesce(p_payload ->> 'currency', 'USD'), p_payload ->> 'store',
            case when (p_payload ->> 'asin') ~ '^[A-Z0-9]{10}$' then p_payload ->> 'asin' end,
            jsonb_build_object('via', 'inbox'))
    returning id into v_id;
    if v_board_kind = 'restaurants' then perform public.sync_restaurant_meals(); end if;
    v_routed := jsonb_build_object('table', 'wishlist_items', 'id', v_id, 'board_kind', v_board_kind);

  elsif p_kind = 'list' then
    v_detected := 'note';
    insert into public.checklists (title, kind)
    values (left(coalesce(nullif(p_payload ->> 'title', ''), 'New list'), 80),
            case when p_payload ->> 'list_kind' in ('grocery', 'todo', 'budget', 'other') then p_payload ->> 'list_kind' else 'todo' end)
    returning id into v_id;
    v_pos := 0;
    for v_item in select * from jsonb_array_elements(coalesce(p_payload -> 'items', '[]'::jsonb)) limit 200 loop
      if length(trim(coalesce(v_item ->> 'body', ''))) > 0 then
        insert into public.checklist_items (checklist_id, body, quantity, is_done, position)
        values (v_id, left(trim(v_item ->> 'body'), 300), left(v_item ->> 'quantity', 40),
                coalesce((v_item ->> 'done')::boolean, false), v_pos);
        v_pos := v_pos + 1;
      end if;
    end loop;
    v_routed := jsonb_build_object('table', 'checklists', 'id', v_id, 'items', v_pos);

  elsif p_kind = 'note' then
    v_detected := 'note';
    select id into v_id from public.checklists where couple_id = v_couple and title = 'Quick notes' and not archived order by created_at limit 1;
    if v_id is null then
      insert into public.checklists (title, kind) values ('Quick notes', 'other') returning id into v_id;
    end if;
    select coalesce(max(position) + 1, 0) into v_pos from public.checklist_items where checklist_id = v_id;
    insert into public.checklist_items (checklist_id, body, position)
    values (v_id, left(trim(coalesce(p_payload ->> 'body', p_raw_text)), 300), v_pos);
    v_routed := jsonb_build_object('table', 'checklists', 'id', v_id, 'items', 1);

  else
    raise exception 'unknown kind';
  end if;

  insert into public.notes_inbox (source, raw_text, raw_url, detected_kind, status, parsed, routed_to)
  values (p_source, left(p_raw_text, 20000), p_raw_url, v_detected, 'routed', p_payload, v_routed);
  return v_routed;
end $$;

-- ---------------------------------------------------------------------
-- 4. Token-authenticated entry points for the iOS Shortcut and the
--    Scriptable widget. A token is created in the app (shown once; only
--    its SHA-256 hash is stored) and acts as that one person.
-- ---------------------------------------------------------------------
create or replace function public.token_user(p_token text)
returns uuid language plpgsql security definer set search_path = '' as $$
declare v_user uuid;
begin
  if p_token is null or p_token !~ '^ci_[0-9a-f]{48}$' then return null; end if;
  update public.inbox_tokens
     set last_used_at = now()
   where token_hash = encode(extensions.digest(p_token, 'sha256'), 'hex') and revoked_at is null
  returning user_id into v_user;
  return v_user;
end $$;

-- Acts as the token's owner for the rest of this transaction: auth.uid(),
-- my_couple_id() and every guard trigger then see that person.
create or replace function public.act_as_token(p_token text)
returns uuid language plpgsql security definer set search_path = '' as $$
declare v_user uuid := public.token_user(p_token);
begin
  if v_user is null then raise exception 'invalid or revoked token' using errcode = '28000'; end if;
  perform set_config('request.jwt.claim.sub', v_user::text, true);
  perform set_config('request.jwt.claims', jsonb_build_object('sub', v_user, 'role', 'authenticated')::text, true);
  return v_user;
end $$;

create or replace function public.inbox_submit(p_token text, p_kind text, p_payload jsonb, p_raw_text text default null, p_raw_url text default null)
returns jsonb language plpgsql security definer set search_path = '' as $$
declare v_user uuid := public.act_as_token(p_token);
begin
  if (select count(*) from public.notes_inbox where created_by = v_user and created_at > now() - interval '10 minutes') >= 60 then
    raise exception 'too many shares, try again in a few minutes';
  end if;
  return public.inbox_save('share_sheet', p_kind, p_payload, p_raw_text, p_raw_url);
end $$;

create or replace function public.inbox_claim_push(p_token text)
returns table (job_id uuid, job_kind text, job_title text, job_body text, job_url text, job_tag text,
               sub_endpoint text, sub_p256dh text, sub_auth text)
language plpgsql security definer set search_path = '' as $$
begin
  perform public.act_as_token(p_token);
  return query select * from public.claim_push_jobs();
end $$;

-- Glanceable numbers for the home-screen widget.
create or replace function public.widget_summary(p_token text)
returns jsonb language plpgsql security definer set search_path = '' as $$
declare
  v_me uuid := public.act_as_token(p_token);
  v_couple uuid := (select couple_id from public.profiles where id = v_me);
  v_partner record;
  v_next record;
  v_out jsonb;
begin
  if v_couple is null then raise exception 'pair with your partner first'; end if;
  select id, display_name, last_seen_at into v_partner from public.profiles where couple_id = v_couple and id <> v_me limit 1;

  select d.title, d.kind, n.on_date, (n.on_date - current_date) as days
    into v_next
  from public.important_dates d
  cross join lateral (
    select (d.starts_on + make_interval(years => (extract(year from current_date) - extract(year from d.starts_on))::int))::date as this_year
  ) y
  cross join lateral (
    select case
      when not d.recurs_yearly then d.starts_on
      when y.this_year >= current_date then y.this_year
      else (d.starts_on + make_interval(years => (extract(year from current_date) - extract(year from d.starts_on))::int + 1))::date
    end as on_date
  ) n
  where d.couple_id = v_couple and n.on_date >= current_date
  order by n.on_date
  limit 1;

  v_out := jsonb_build_object(
    'me', (select display_name from public.profiles where id = v_me),
    'partner', v_partner.display_name,
    'partner_seen_at', v_partner.last_seen_at,
    'unwatched_tiktoks', (select count(*) from public.tiktok_videos v
                          where v.couple_id = v_couple and v.sent_by <> v_me
                            and not exists (select 1 from public.tiktok_views w where w.video_id = v.id and w.user_id = v_me)),
    'open_items', (select count(*) from public.checklist_items i join public.checklists c on c.id = i.checklist_id
                   where i.couple_id = v_couple and not i.is_done and not c.archived),
    'bills_due_week', (select count(*) from public.bills b
                       where b.couple_id = v_couple and b.active and b.next_due_on <= current_date + 7),
    'next_date', case when v_next.title is null then null
                      else jsonb_build_object('title', v_next.title, 'kind', v_next.kind, 'on', v_next.on_date, 'days', v_next.days) end,
    'updated_at', now()
  );
  return v_out;
end $$;

